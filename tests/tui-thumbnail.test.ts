import { afterEach, describe, expect, it, vi } from 'vitest'
import { BrowserStateStore } from '../src/browser-state.ts'
import { createThumbnailController } from '../src/tui/thumbnail.ts'

const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAYAAABytg0kAAAAGklEQVR4nGPgEpH7b2Ok0cBwYssCBxGNAAYAL2AFOuzF1YgAAAAASUVORK5CYII=', 'base64')
const wire = () => ({ ensureWorker: vi.fn(async () => 1234), requestSnapshot: vi.fn(async () => png as Uint8Array | null) })
afterEach(() => vi.useRealTimers())

describe('event-driven TUI thumbnails', () => {
  it('captures on visible selection, tool completion, and manual refresh, never on a timer', async () => {
    vi.useFakeTimers()
    const store = new BrowserStateStore(), transport = wire()
    const controller = createThumbnailController(store, { disableFrameRelay: false }, transport)
    controller.setView(true, 'first', 224)
    await vi.advanceTimersByTimeAsync(0)
    expect(transport.requestSnapshot).toHaveBeenCalledWith(1234, 'first', 224)
    const first = controller.getSnapshot().source!
    expect(first.width).toBe(2)
    expect(first.height).toBe(2)
    expect([...first.data.slice(0, 4)]).toEqual([10, 20, 30, 255])
    await vi.advanceTimersByTimeAsync(60_000)
    expect(transport.requestSnapshot).toHaveBeenCalledTimes(1)
    controller.setView(true, 'second', 224)
    await vi.advanceTimersByTimeAsync(0)
    expect(transport.requestSnapshot).toHaveBeenLastCalledWith(1234, 'second', 224)
    const token = store.startTool('ego_click', '#submit')
    store.finishTool(token, { ok: true })
    await vi.advanceTimersByTimeAsync(0)
    expect(transport.requestSnapshot).toHaveBeenCalledTimes(3)
    await controller.refresh()
    expect(transport.requestSnapshot).toHaveBeenCalledTimes(4)
    expect(controller.getSnapshot().source!.data).not.toBe(first.data)
    controller.setView(false, 'second', 224)
    const hidden = store.startTool('ego_click', '#submit')
    store.finishTool(hidden, { ok: true })
    await controller.refresh()
    expect(transport.requestSnapshot).toHaveBeenCalledTimes(4)
    controller.dispose()
  })
  it('never requests worker startup or pixels with relay disabled', async () => {
    const store = new BrowserStateStore(), transport = wire()
    const controller = createThumbnailController(store, { disableFrameRelay: true }, transport)
    controller.setView(true, 'first', 224)
    await controller.refresh()
    expect(transport.ensureWorker).not.toHaveBeenCalled()
    expect(transport.requestSnapshot).not.toHaveBeenCalled()
    expect(controller.getSnapshot().alt).toContain('disabled')
    controller.dispose()
  })
  it('drops stale pixels and captures the latest tab after a pending selection changes', async () => {
    const store = new BrowserStateStore(), transport = wire()
    let release!: (bytes: Uint8Array | null) => void
    transport.requestSnapshot.mockImplementationOnce(() => new Promise(resolve => { release = resolve }))
    const controller = createThumbnailController(store, { disableFrameRelay: false }, transport)
    controller.setView(true, 'first', 224)
    await vi.waitFor(() => expect(transport.requestSnapshot).toHaveBeenCalledOnce())
    controller.setView(true, 'second', 224)
    release(png)
    await vi.waitFor(() => expect(transport.requestSnapshot).toHaveBeenCalledTimes(2))
    expect(transport.requestSnapshot).toHaveBeenLastCalledWith(1234, 'second', 224)
    expect(controller.getSnapshot().source?.width).toBe(2)
    controller.dispose()
  })
  it('stops before capture if hidden while worker acquisition is pending', async () => {
    const store = new BrowserStateStore(), transport = wire()
    let release!: (port: number) => void
    transport.ensureWorker.mockImplementationOnce(() => new Promise(resolve => { release = resolve }))
    const controller = createThumbnailController(store, { disableFrameRelay: false }, transport)
    controller.setView(true, 'first', 224)
    controller.setView(false, 'first', 224)
    release(1234)
    await controller.refresh()
    await Promise.resolve()
    expect(transport.requestSnapshot).not.toHaveBeenCalled()
    controller.dispose()
  })
  it('provides a text fallback for unavailable and malformed frames, with no callbacks after disposal', async () => {
    const store = new BrowserStateStore(), transport = wire()
    transport.requestSnapshot.mockResolvedValue(null)
    const controller = createThumbnailController(store, { disableFrameRelay: false }, transport)
    const listener = vi.fn()
    controller.subscribe(listener)
    controller.setView(true, 'first', 224)
    await vi.waitFor(() => expect(controller.getSnapshot().alt).toContain('unavailable'))
    expect(controller.getSnapshot().source).toBeUndefined()
    transport.requestSnapshot.mockResolvedValue(new Uint8Array([1, 2, 3]))
    await controller.refresh()
    expect(controller.getSnapshot().source).toBeUndefined()
    controller.dispose()
    listener.mockClear()
    await controller.refresh()
    expect(listener).not.toHaveBeenCalled()
  })
})
